const ITEMS: { key: TermsKey; required: boolean; label: string; Content: () => ReactElement }[] = [
  { key: "terms", required: true, label: "이용약관 동의 (환불·청약철회 정책 포함)", Content: TermsContent },
  { key: "privacy", required: true, label: "개인정보 수집·이용 동의", Content: PrivacyContent },
  { key: "privacyIntl", required: true, label: "개인정보 국외이전 동의 (AI 채점 · 서버 호스팅)", Content: PrivacyIntlContent },
  { key: "marketing", required: false, label: "마케팅 정보 수신 동의", Content: MarketingContent },
  { key: "photo", required: false, label: "후기·사진 홍보 목적 이용 동의", Content: PhotoContent },
];

export function TermsAgreement({
  values,
  onChange,
}: {
  values: TermsValues;
  onChange: (next: TermsValues) => void;
}) {
  const [expanded, setExpanded] = useState<Record<TermsKey, boolean>>({
    terms: false,
    privacy: false,
    privacyIntl: false,
    marketing: false,
    photo: false,
  });

  const allChecked = ITEMS.every((item) => values[item.key]);

  const toggleAll = (checked: boolean) => {
    const next = { ...values };
    ITEMS.forEach((item) => {
      next[item.key] = checked;
    });
    onChange(next);
  };

  const toggleOne = (key: TermsKey, checked: boolean) => {
    onChange({ ...values, [key]: checked });
  };

  const toggleExpand = (key: TermsKey) => {
    setExpanded((prev) => ({ ...prev, [key]: !prev[key] }));
  };

  return (
    <div className="terms-block">
      <label className="terms-row terms-row-all">
        <input type="checkbox" checked={allChecked} onChange={(e) => toggleAll(e.target.checked)} />
        <span>전체 동의</span>
      </label>
      <div className="terms-divider" />
      {ITEMS.map((item) => (
        <div key={item.key}>
          <div className="terms-row">
            <label className="terms-checkbox-label">
              <input
                type="checkbox"
                checked={values[item.key]}
                onChange={(e) => toggleOne(item.key, e.target.checked)}
              />
              <span className={`terms-tag ${item.required ? "required" : "optional"}`}>
                {item.required ? "필수" : "선택"}
              </span>
              {item.label}
            </label>
            <button type="button" className="terms-view-toggle" onClick={() => toggleExpand(item.key)}>
              {expanded[item.key] ? "접기" : "보기"}
            </button>
          </div>
          {expanded[item.key] && (
            <div className="terms-content">
              <item.Content />
            </div>
          )}
        </div>
      ))}
    </div>
  );
}
